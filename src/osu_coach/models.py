"""Database tables.

Nullability matches the osu! API models in osu_coach.osu.schemas: a field that osu! can
send as null is `Mapped[X | None]` here, so syncing real data never hits NOT NULL errors.
"""

from datetime import datetime

from sqlalchemy import (
    BigInteger,
    DateTime,
    Float,
    ForeignKey,
    Identity,
    Index,
    Integer,
    MetaData,
    String,
    func,
)
from sqlalchemy.dialects.postgresql import ARRAY
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column


class Base(DeclarativeBase):
    # Name every constraint predictably, so migrations can refer to them (for example to
    # drop a foreign key on downgrade). These match the names Postgres picks by itself,
    # so constraints created before this convention keep the same names.
    metadata = MetaData(
        naming_convention={
            "ix": "ix_%(column_0_label)s",
            "uq": "%(table_name)s_%(column_0_name)s_key",
            "ck": "%(table_name)s_%(constraint_name)s_check",
            "fk": "%(table_name)s_%(column_0_name)s_fkey",
            "pk": "%(table_name)s_pkey",
        }
    )


class Player(Base):
    __tablename__ = "players"

    # osu! assigns the id, so it's not generated by the database.
    osu_id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=False)
    # Indexed for lookups by name; not unique, since osu! names can change and be reused.
    username: Mapped[str] = mapped_column(String(32), index=True)  # osu! names: max 15
    country: Mapped[str] = mapped_column(String(2))
    global_rank: Mapped[int | None] = mapped_column(Integer)  # null for inactive players
    pp: Mapped[float] = mapped_column(Float)
    playcount: Mapped[int] = mapped_column(Integer)
    accuracy: Mapped[float] = mapped_column(Float)  # a percent (96.85), unlike scores
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )


class Beatmap(Base):
    """One difficulty of a map (what osu! calls a beatmap)."""

    __tablename__ = "beatmaps"

    # osu! assigns the id, so it's not generated by the database.
    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=False)
    beatmapset_id: Mapped[int] = mapped_column(BigInteger)
    artist: Mapped[str] = mapped_column(String(255))
    title: Mapped[str] = mapped_column(String(255))
    creator: Mapped[str] = mapped_column(String(32))  # the mapper's username
    version: Mapped[str] = mapped_column(String(255))  # the difficulty name, e.g. "Hard"
    star_rating: Mapped[float] = mapped_column(Float)
    ar: Mapped[float] = mapped_column(Float)
    od: Mapped[float] = mapped_column(Float)
    cs: Mapped[float] = mapped_column(Float)
    hp: Mapped[float] = mapped_column(Float)
    bpm: Mapped[float] = mapped_column(Float)
    length_s: Mapped[int] = mapped_column(Integer)  # including breaks
    hit_length_s: Mapped[int] = mapped_column(Integer)  # actual play time
    count_circles: Mapped[int] = mapped_column(Integer)
    count_sliders: Mapped[int] = mapped_column(Integer)
    count_spinners: Mapped[int] = mapped_column(Integer)
    max_combo: Mapped[int | None] = mapped_column(Integer)  # osu! can send null
    # MD5 of the .osu file: a replay finds its map by this. Unique (one row per file),
    # and Postgres allows any number of NULLs in a unique column.
    checksum: Mapped[str | None] = mapped_column(String(32), unique=True)
    status: Mapped[str] = mapped_column(String(16))  # "ranked", "loved", ...
    mode: Mapped[str] = mapped_column(String(16))  # "osu" for standard
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now()
    )


class Score(Base):
    __tablename__ = "scores"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True, autoincrement=False)
    # CASCADE: deleting a player deletes their scores, so no orphans are left.
    player_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("players.osu_id", ondelete="CASCADE")
    )
    # No ondelete: deleting a map that has scores is almost certainly a mistake, so
    # Postgres refuses it. Indexed for per-map queries.
    beatmap_id: Mapped[int] = mapped_column(BigInteger, ForeignKey("beatmaps.id"), index=True)
    score: Mapped[int] = mapped_column(BigInteger)
    max_combo: Mapped[int] = mapped_column(Integer)
    count_300: Mapped[int] = mapped_column(Integer)
    count_100: Mapped[int] = mapped_column(Integer)
    count_50: Mapped[int] = mapped_column(Integer)
    count_miss: Mapped[int] = mapped_column(Integer)
    rank: Mapped[str] = mapped_column(String(2))
    pp: Mapped[float | None] = mapped_column(Float)  # null for failed plays, unranked maps
    mods: Mapped[list[str]] = mapped_column(ARRAY(String))
    # When the play happened, from osu!. No default: a missing value must fail, not
    # silently become the sync time.
    date: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    accuracy: Mapped[float] = mapped_column(Float)  # 0-1
    passed: Mapped[bool]

    # "This player's scores by pp" in one index scan. Postgres doesn't index foreign keys
    # on its own, and this also covers lookups by player_id alone.
    __table_args__ = (Index("ix_scores_player_pp", "player_id", "pp"),)


class BeatmapObject(Base):
    """One hit object of a map, with its pattern features (see osu_coach.patterns)."""

    __tablename__ = "hit_objects"

    # CASCADE: the objects belong to the map; deleting the map removes them.
    beatmap_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("beatmaps.id", ondelete="CASCADE"), primary_key=True
    )
    idx: Mapped[int] = mapped_column(Integer, primary_key=True)  # order in the map, from 0
    kind: Mapped[str] = mapped_column(String(8))  # "circle", "slider" or "spinner"
    time_ms: Mapped[int] = mapped_column(Integer)
    end_time_ms: Mapped[int] = mapped_column(Integer)  # sliders and spinners last a while
    x: Mapped[float] = mapped_column(Float)  # osu! pixels: 0-512 wide, 0-384 tall
    y: Mapped[float] = mapped_column(Float)
    # Not defined for the first object or around spinners:
    spacing: Mapped[float | None] = mapped_column(Float)  # osu! pixels from the previous
    angle: Mapped[float | None] = mapped_column(Float)  # degrees, 0-180
    time_since_prev_ms: Mapped[int | None] = mapped_column(Integer)
    pattern: Mapped[str] = mapped_column(String(16))  # jump, stream, slider, spinner, other

    # The primary key (beatmap_id, idx) already serves "all objects of a map, in order".
    # This one serves "misses by pattern" once replays are analyzed.
    __table_args__ = (Index("ix_hit_objects_pattern", "pattern"),)


class Replay(Base):
    """An uploaded replay: who played which map, the result, and where its frames are."""

    __tablename__ = "replays"

    id: Mapped[int] = mapped_column(BigInteger, Identity(), primary_key=True)
    # SHA-256 of the uploaded file: uploading the same file again finds this row.
    file_sha256: Mapped[str] = mapped_column(String(64), unique=True)
    # The map, by its .osu file's MD5. Not a foreign key: the map may not be fetched yet,
    # and joining on beatmaps.checksum only matches the exact version that was played.
    beatmap_checksum: Mapped[str] = mapped_column(String(32), index=True)
    # The online score. Not a foreign key either: only top and recent plays are synced.
    score_id: Mapped[int | None] = mapped_column(BigInteger)
    player_name: Mapped[str] = mapped_column(String(32))  # the replay has no player id
    mods: Mapped[list[str]] = mapped_column(ARRAY(String))
    lazer: Mapped[bool]
    game_version: Mapped[int] = mapped_column(Integer)
    count_300: Mapped[int] = mapped_column(Integer)
    count_100: Mapped[int] = mapped_column(Integer)
    count_50: Mapped[int] = mapped_column(Integer)
    count_geki: Mapped[int] = mapped_column(Integer)
    count_katu: Mapped[int] = mapped_column(Integer)
    count_miss: Mapped[int] = mapped_column(Integer)
    score: Mapped[int] = mapped_column(BigInteger)
    max_combo: Mapped[int] = mapped_column(Integer)
    perfect: Mapped[bool]
    played_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    frame_count: Mapped[int] = mapped_column(Integer)
    # The frames' Parquet file, relative to the data folder (it moves between machines).
    frames_path: Mapped[str] = mapped_column(String(255))
    parsed_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())

    # Set once the replay is analyzed (see osu_coach.analysis); null until then.
    # The map it was judged against. No ondelete, like scores: deleting an analyzed map
    # is almost certainly a mistake.
    beatmap_id: Mapped[int | None] = mapped_column(BigInteger, ForeignKey("beatmaps.id"))
    unstable_rate: Mapped[float | None] = mapped_column(Float)  # 10 x the timing's spread
    mean_error_ms: Mapped[float | None] = mapped_column(Float)  # negative: early on average
    mean_aim_error_px: Mapped[float | None] = mapped_column(Float)  # from circle centers
    analyzed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class ReplayHit(Base):
    """How one circle or slider head of a replay was hit (see osu_coach.judge)."""

    __tablename__ = "hit_results"

    # CASCADE: the results belong to the replay; deleting it removes them.
    replay_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("replays.id", ondelete="CASCADE"), primary_key=True
    )
    # The object's place in the map: joins hit_objects on (replays.beatmap_id, idx).
    idx: Mapped[int] = mapped_column(Integer, primary_key=True)
    result: Mapped[str] = mapped_column(String(4))  # "300", "100", "50" or "miss"
    hit_ms: Mapped[int | None] = mapped_column(Integer)  # when it was hit; null if never
    error_ms: Mapped[int | None] = mapped_column(Integer)  # negative is early
    aim_error_px: Mapped[float | None] = mapped_column(Float)  # cursor to circle center
    forced: Mapped[bool]  # missed because a later circle was hit first (note lock)
